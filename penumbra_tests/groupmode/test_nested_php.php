function group_by_tokens($token, $data, $customSortOrders = array()) {
    $first = reset($data);
    $levels = array(); $cmps = array();
    foreach (penumbra_group_levels($token) as $tok) {
        $spec = penumbra_group_level_spec($tok, $first, $data, $customSortOrders);
        if ($spec === null) break;
        $levels[] = $spec; $cmps[] = $spec['cmp'];
    }
    $out = array();
    penumbra_group_rows_nested($data, $levels, $cmps, 0, '', $out);
    return $out;
}
