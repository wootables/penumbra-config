                }
            }
            return $out;
        }
        function xlsx_shared($entries) {
            $s = isset($entries['xl/sharedStrings.xml']) ? $entries['xl/sharedStrings.xml'] : '';
            preg_match_all('/<si><t[^>]*>(.*?)<\/t><\/si>/s', $s, $m);
            return $m[1];
        }
        // Rows that are a single shared-string cell in column A = the bands.
        function xlsx_bands($xml, $si) {
            $out = array();
            if (preg_match_all('/<row r="(\d+)"([^>]*)>(.*?)<\/row>/s', $xml, $m, PREG_SET_ORDER)) {
                foreach ($m as $r) {
                    if (substr_count($r[3], '<c ') !== 1) continue;
