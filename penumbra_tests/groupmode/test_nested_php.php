        eq('php xlsx nested: collapses to ONE sheet', xlsx_sheet_count($xe2), 1);
        ok('php xlsx nested: named Grouped Data',
            strpos($xe2['xl/workbook.xml'], '<sheet name="Grouped Data"') !== false, '');
        ok('php xlsx nested: outline bands sit ABOVE their detail',
            strpos($xs2, '<outlinePr summaryBelow="0"') !== false, '');
        // Both halves must EXIST before their order means anything: strpos()
        // returns false when a needle is missing, and `false < <int>` is true,
        // so the naive comparison passes on a build emitting no sheetPr at all.
        $_pPr = strpos($xs2, '<sheetPr>');
        $_pViews = strpos($xs2, '<sheetViews>');
        ok('php xlsx nested: sheetPr precedes sheetViews (schema order)',
            $_pPr !== false && $_pViews !== false && $_pPr < $_pViews,
            'sheetPr@' . var_export($_pPr, true) . ' sheetViews@' . var_export($_pViews, true));
        $_pData = strpos($xs2, '</sheetData>');
        $_pMerge = strpos($xs2, '<mergeCells');
        ok('php xlsx nested: mergeCells FOLLOWS sheetData (schema order)',
            $_pData !== false && $_pMerge !== false && $_pData < $_pMerge,
            'sheetData@' . var_export($_pData, true) . ' mergeCells@' . var_export($_pMerge, true));

        $lv2 = xlsx_levels($xs2);
        eq('php xlsx nested: the column header carries no outline level', $lv2[1], null);
        eq('php xlsx nested: row 2 is a depth-0 band', $lv2[2], 0);
        eq('php xlsx nested: row 3 is a depth-1 band', $lv2[3], 1);
        eq('php xlsx nested: data sits one level below its band', $lv2[4], 2);
        eq('php xlsx nested: 6 bands + 6 data + header + footer', count($lv2), 14);

        $bands2 = xlsx_bands($xs2, xlsx_shared($xe2));
        eq('php xlsx nested: one band per node, none per row', count($bands2), 6);
        eq('php xlsx nested: bands name the segment and their SUBTREE count',
            array_map(function ($b) { return $b['text']; }, $bands2),
            array('Eng   (3)', 'ECE   (2)', 'ME   (1)', 'Sci   (3)', 'BIO   (2)', 'CHEM   (1)'));
        ok('php xlsx nested: one merge per band',
            preg_match('/<mergeCells count="6">/', $xs2) === 1, '');

        // Three levels must go four deep, and the middle bucket level keeps
        // calendar order rather than being re-sorted as text.
        $xe3 = xlsx_entries($g3);
        $xs3 = xlsx_sheet_xml($xe3);
        eq('php xlsx 3 levels: still ONE sheet', xlsx_sheet_count($xe3), 1);
        $b3 = xlsx_bands($xs3, xlsx_shared($xe3));
        eq('php xlsx 3 levels: data reaches outline level 3', max(array_filter(xlsx_levels($xs3), 'is_int')), 3);
        eq('php xlsx 3 levels: bands nest college > fiscal year > dept',
            array_map(function ($b) { return $b['text'] . '@' . $b['level']; }, array_slice($b3, 0, 4)),
            array('Eng   (3)@0', 'FY24   (2)@1', 'ECE   (1)@2', 'ME   (1)@2'));

        // A SINGLE-level grouping must keep the untouched per-sheet export.
        $xe1 = xlsx_entries(group_by_tokens('COLLEGE', $DATA));
        eq('php xlsx one level: still one sheet PER GROUP', xlsx_sheet_count($xe1), 2);
        ok('php xlsx one level: sheets keep their group names + counts',
            strpos($xe1['xl/workbook.xml'], '<sheet name="Eng (3)"') !== false, '');
        ok('php xlsx one level: and no outline machinery at all',
            strpos(xlsx_sheet_xml($xe1), 'outlineLevel') === false
            && strpos(xlsx_sheet_xml($xe1), '<sheetPr>') === false, '');
    }

    // ---- band SHAPE: an ancestor is a heading, a leaf is a table cap ----
    // $groupHeaderCss is built for the cap case (`border-radius: 8px 8px 0 0`
    // with `border-bottom: none`) so the table below closes the box. An
    // ancestor has another band beneath it instead, so reusing the cap shape
    // left an un-closed box with a rounded top nested inside it.
    ok('php email: the ancestor band is rounded on all four corners',
        strpos($html2, 'border-radius: 8px;') !== false, '');
    ok('php email: and gets its bottom border back so the box closes',
        preg_match('/border-bottom: 1px solid [^;]+; border-radius: 8px;/', $html2) === 1, '');
    ok('php email: the leaf band still caps its table',
        strpos($html2, 'border-radius: 8px 8px 0 0;') !== false, '');
    // One heading shape per ancestor, one cap per leaf.
    eq('php email: one rounded heading per ancestor band',
        substr_count($html2, 'border-radius: 8px;'), 2);

    // A SINGLE-level grouping must be byte-identical to the pre-nesting output.
    $g1 = group_by_tokens('COLLEGE', $DATA);
    $html1 = generate_report_html($g1, 'grouped', 'theme-default', 'T', false, '', true,
        null, '', '', '', null, array(), $agg);
    ok('php email: one level draws no ancestor band and no indent',
        strpos($html1, 'margin-left: 0px') === false && strpos($html1, 'margin-left: 18px') === false,
        'a flat grouping must render exactly as before');
    ok('php email: one level keeps the cap shape and adds no heading shape',
        strpos($html1, 'border-radius: 8px 8px 0 0;') !== false
        && strpos($html1, 'border-radius: 8px;') === false,
        'a flat grouping must not pick up the ancestor heading shape');
    ok('php email: one level still names its group', strpos($html1, '>Eng <') !== false, '');

    // ===== Grouping on a column the report HIDES (2026-09-01) ================
    // ?id=eirbprotsum groups by PROTOCOL TYPE, which is not in visibleColumns.
    // apply_state_logic() force-adds such a column so the grouping can read it
    // and strips it back out afterwards - but the strip used to run BEFORE
    // penumbra_group_rows_nested(), deleting the value that walk labels each row
    // by. Every row came back unlabelled, collapsed into one "[Blank]" band, and
    // the mail showed a single group holding the whole report while the browser
    // showed four. Drives the REAL apply_state_logic(), not a reimplementation.
    $hidCols = array('PROTOCOL NO', 'APPROVAL DATE', 'NAME', 'DEPARTMENT', 'COLLEGE',
                     'TITLE', 'APPROVAL BEGIN', 'APPROVAL END', 'HS_POINT_CONTACT',
                     'HS_POINT_CONTACT_DEPT', 'HS_ROUTING_LEVEL_DESCRIP',
                     'HS_ROUTING_STATUS_DESCRIP', 'HS_RENEW_TRK_NUMB', 'PROTOCOL TYPE');
    $hidTypes = array('Amendment/Renewals' => 33, 'Exempt Protocols' => 36,
                      'Expedited Studies' => 12, 'Full Board Review' => 2);
    $hidData = array(); $hidN = 0;
    foreach ($hidTypes as $t => $c) {
        for ($i = 0; $i < $c; $i++) {
            $r = array();
            foreach ($hidCols as $col) { $r[$col] = ($col === 'PROTOCOL TYPE') ? $t : ($col . '-' . $hidN); }
            $hidData[] = $r; $hidN++;
        }
    }
    // visibleColumns deliberately omits index 13 (PROTOCOL TYPE) - the live state.
    $hidState = array(
        'groupBy'        => 'PROTOCOL TYPE',
        'visibleColumns' => array(0, 4, 7, 8, 9, 1, 2, 3),
        'columnOrder'    => array(0, 4, 7, 8, 9, 1, 2, 3, 5, 6, 10, 11, 12, 13),
    );
    $hidRes = apply_state_logic($hidData, $hidState);
    $hidOut = $hidRes['data'];

    eq('php hidden group col: the view is grouped at all', $hidRes['viewMode'], 'grouped');
    eq('php hidden group col: one band per distinct value, not one [Blank]',
        count($hidOut), 4);
    ok('php hidden group col: no [Blank] band at all',
        !array_key_exists('[Blank]', $hidOut), implode(' | ', array_keys($hidOut)));
    eq('php hidden group col: the bands are the real values',
        implode('|', array_keys($hidOut)),
        'Amendment/Renewals|Exempt Protocols|Expedited Studies|Full Board Review');
    eq('php hidden group col: counts match the browser', json_encode(counts($hidOut)),
        json_encode(array('Amendment/Renewals' => 33, 'Exempt Protocols' => 36,
                          'Expedited Studies' => 12, 'Full Board Review' => 2)));
    eq('php hidden group col: every row still present exactly once',
        rowTotal($hidOut), count($hidData));
    // The strip must still HAPPEN - it just has to happen last. A fix that only
    // moved the walk earlier would leak the hidden column into the email.
    $hidLeaked = false;
    foreach ($hidOut as $rows) {
        foreach ($rows as $r) { if (array_key_exists('PROTOCOL TYPE', $r)) { $hidLeaked = true; break 2; } }
    }
    ok('php hidden group col: the forced-visible column is still stripped',
        !$hidLeaked, 'PROTOCOL TYPE leaked into the emailed rows');
    // A VISIBLE grouping column must survive untouched - it is a real column of
    // the report, not one borrowed for the walk.
    $visState = array(
        'groupBy'        => 'PROTOCOL TYPE',
        'visibleColumns' => array(0, 4, 7, 13),
        'columnOrder'    => array(0, 4, 7, 13),
    );
    $visOut = apply_state_logic($hidData, $visState);
    $visKept = true;
    foreach ($visOut['data'] as $rows) {
        foreach ($rows as $r) { if (!array_key_exists('PROTOCOL TYPE', $r)) { $visKept = false; break 2; } }
    }
    eq('php visible group col: still four bands', count($visOut['data']), 4);
    ok('php visible group col: a VISIBLE grouping column is NOT stripped', $visKept,
        'a column the report actually shows must survive');

    echo 'RESULTS_JSON:' . json_encode(array('results' => $results));
} catch (Throwable $e) {
    echo 'RESULTS_JSON:' . json_encode(array(
        'fatal' => $e->getMessage() . ' @' . $e->getFile() . ':' . $e->getLine(),
        'results' => $results));
}
