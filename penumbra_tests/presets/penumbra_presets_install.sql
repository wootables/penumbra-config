-- PENUMBRA_PRESETS: shared presets for the preset engine (manage_presets.php).
-- Run as the NC_REPORTING owner (or an account with CREATE ANY TABLE and GRANT rights).
-- The app connects as ORIED_RO with CURRENT_SCHEMA = NC_Reporting, so the table
-- must live in NC_REPORTING and that account needs the four DML privileges on it.
-- Pre-12c Oracle (identity column rejected): use the `legacy` statements from install&dry=1.
--
-- This is the same text manage_presets.php returns from action=install&dry=1
-- (and from a refused install), kept here so it can be handed over without
-- signing in. Regenerate from the endpoint if the table shape ever changes.

CREATE TABLE NC_REPORTING.PENUMBRA_PRESETS (
    ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    REPORT_ID   NUMBER NOT NULL,
    NS          VARCHAR2(20) NOT NULL,
    NAME        VARCHAR2(200 CHAR) NOT NULL,
    DATA        CLOB NOT NULL,
    CREATED_BY  VARCHAR2(100),
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_BY  VARCHAR2(100),
    UPDATED_AT  TIMESTAMP,
    CONSTRAINT PK_PENUMBRA_PRESETS PRIMARY KEY (ID),
    CONSTRAINT UQ_PENUMBRA_PRESET UNIQUE (REPORT_ID, NS, NAME)
);

GRANT SELECT, INSERT, UPDATE, DELETE ON NC_REPORTING.PENUMBRA_PRESETS TO ORIED_RO;

