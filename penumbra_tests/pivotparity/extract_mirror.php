<?php
/**
 * Extract the pivot mirror out of schedule_runner.php WITHOUT executing it.
 *
 * schedule_runner.php is a CLI entry point: its top level connects to Oracle,
 * claims scheduled tasks and SENDS EMAIL. It must never be require()d from a
 * test. So we lift only the top-level `function` declarations (plus top-level
 * define()s - a prior extraction dropped those and the constants went missing)
 * into a standalone, side-effect-free file.
 *
 * Uses PHP's own tokenizer rather than brace counting: a 1.4MB file has braces
 * inside strings, comments and heredocs, and a naive counter mis-slices them.
 *
 *   php extract_mirror.php <source.php> <out.php>
 */
if ($argc < 3) { fwrite(STDERR, "usage: extract_mirror.php <src> <out>\n"); exit(2); }
$src = $argv[1];
$out = $argv[2];
$code = file_get_contents($src);
if ($code === false) { fwrite(STDERR, "cannot read $src\n"); exit(2); }

$tokens = token_get_all($code);
$depth = 0;          // brace depth
$parens = 0;         // paren depth (a function's param list)
$n = count($tokens);
$pieces = array();
$defines = array();
$names = array();

for ($i = 0; $i < $n; $i++) {
    $t = $tokens[$i];

    // ---- top-level define('X', ...) --------------------------------------
    if ($depth === 0 && is_array($t) && $t[0] === T_STRING && strtolower($t[1]) === 'define') {
        $j = $i; $buf = ''; $p = 0; $started = false;
        for (; $j < $n; $j++) {
            $tt = $tokens[$j];
            $txt = is_array($tt) ? $tt[1] : $tt;
            $buf .= $txt;
            if ($txt === '(') { $p++; $started = true; }
            elseif ($txt === ')') { $p--; if ($started && $p === 0) { break; } }
        }
        // consume trailing ';'
        for ($k = $j + 1; $k < $n; $k++) {
            $tt = $tokens[$k]; $txt = is_array($tt) ? $tt[1] : $tt;
            if (trim($txt) === '') { continue; }
            if ($txt === ';') { $buf .= ';'; $j = $k; }
            break;
        }
        $defines[] = $buf;
        $i = $j;
        continue;
    }

    // ---- top-level named function ----------------------------------------
    if ($depth === 0 && is_array($t) && $t[0] === T_FUNCTION) {
        // Require a NAME after `function` so closures assigned at top level
        // ($x = function () {...}) are not mistaken for declarations.
        $k = $i + 1;
        while ($k < $n && is_array($tokens[$k]) && in_array($tokens[$k][0], array(T_WHITESPACE, T_COMMENT, T_DOC_COMMENT), true)) { $k++; }
        if (!($k < $n && is_array($tokens[$k]) && $tokens[$k][0] === T_STRING)) { continue; }
        $fname = $tokens[$k][1];

        $buf = ''; $d = 0; $opened = false;
        for ($j = $i; $j < $n; $j++) {
            $tt = $tokens[$j];
            $txt = is_array($tt) ? $tt[1] : $tt;
            $buf .= $txt;
            if ($txt === '{') { $d++; $opened = true; }
            elseif ($txt === '}') { $d--; if ($opened && $d === 0) { break; } }
        }
        if (!$opened) { continue; }          // abstract/interface style - skip
        $pieces[] = $buf;
        $names[] = $fname;
        $i = $j;
        continue;
    }

    // ---- depth tracking ---------------------------------------------------
    if (!is_array($t)) {
        if ($t === '{') { $depth++; }
        elseif ($t === '}') { $depth--; }
    } elseif ($t[0] === T_CURLY_OPEN || $t[0] === T_DOLLAR_OPEN_CURLY_BRACES) {
        $depth++;
    }
}

$hdr  = "<?php\n";
$hdr .= "// GENERATED by extract_mirror.php from " . basename($src) . " - DO NOT EDIT.\n";
$hdr .= "// Top-level function declarations only: no requires, no DB, no side effects.\n";
$hdr .= "// " . count($pieces) . " functions, " . count($defines) . " defines.\n\n";
foreach ($defines as $d) { $hdr .= "if (!defined(" . _first_arg($d) . ")) { $d }\n"; }
$hdr .= "\n";

// The CSV formula guard (2026-10-01 security sweep) lives in shared_logic.php,
// which the runner requires but a mirror cannot (it requires db_connection.php).
// When the runner CALLS the guard, lift its two functions from shared_logic.php
// by text - the stage's copy beside the source if there is one, else live's -
// so every suite that builds CSV through the mirror works (2026-10-04; before
// this, generate_pivot_csv_string died on "undefined function").
if (strpos($code, 'penumbraCsvGuardRow(') !== false && !in_array('penumbraCsvGuardRow', $names, true)) {
    $sl = dirname($src) . '/shared_logic.php';
    if (!file_exists($sl)) $sl = '\\\\oitras.oit.ncsu.edu\\c$\\inetpub\\wwwroot\\sponsor_migration\\penumbra\\shared_logic.php';
    $slCode = @file_get_contents($sl);
    $ga = ($slCode === false) ? false : strpos($slCode, 'function penumbraCsvGuardCell(');
    $gb = ($ga === false) ? false : strpos($slCode, '// -- end of the CSV formula guard --', $ga);
    if ($ga === false || $gb === false) { fwrite(STDERR, "CSV guard functions not found in $sl\n"); exit(2); }
    $pieces[] = "// Lifted from " . basename($sl) . " (the CSV formula guard the runner calls)\n"
              . "if (!function_exists('penumbraCsvGuardCell')) {\n" . rtrim(substr($slCode, $ga, $gb - $ga)) . "\n}";
}

file_put_contents($out, $hdr . implode("\n\n", $pieces) . "\n");
fwrite(STDOUT, "extracted " . count($pieces) . " functions, " . count($defines) . " defines -> $out\n");

// Pull the first argument of a define(...) call so we can guard it.
function _first_arg($defineCall) {
    if (preg_match('/define\s*\(\s*([\'"][^\'"]*[\'"])/', $defineCall, $m)) { return $m[1]; }
    return "''";
}
